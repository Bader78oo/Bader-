// Derived per-creature lines: question (q_), answer (a_), fact (f_), and zone descriptions (z_).
(() => {
  const L = window.LESSON;
  const zone = id => L.zones.find(z => z.id === id);
  const verb = c => c.plant ? (c.f ? 'تَنْمُو' : 'يَنْمُو') : (c.f ? 'تَعِيشُ' : 'يَعِيشُ');
  const verbDialect = c => c.plant ? (c.f ? 'تنمو' : 'ينمو') : (c.f ? 'تعيش' : 'يعيش');
  L.verb = verb;
  for (const c of L.creatures) {
    L.lines['q_' + c.id] = `وين ${verbDialect(c)} ${c.name}؟`;
    L.lines['a_' + c.id] = `${c.name} ${verb(c)} فِي ${zone(c.zone).name.replace(/ُ$/, 'ِ')}.`;
    L.lines['f_' + c.id] = `${L.lines['a_' + c.id]} ${c.fact}`;
  }
  for (const z of L.zones) L.lines['z_' + z.id] = z.about;
})();
